#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
"""Conformance runner (P2-05, FR-11.1–11.4).

For every scenario: build the host `.so`, run it, canonicalise the trace, and
compare it with the committed reference. The reference directory is selected
in this order:

    conformance/oracle/qnx/        captured with the SDP (preferred)
    conformance/oracle/simulator/  generated by this simulator (fallback)

The fallback is a regression baseline, not evidence about QNX. The report says
which source was used, and docs/CONFORMANCE.md states the limitation.

`--record` rebuilds the simulator references. It refuses to overwrite a QNX
capture.

Usage:
    python3 conformance/runner/run_conformance.py [--record] [--verbose]
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from conformance.tracecmp import (canonicalise, compare_events, to_jsonl,
                                  load_canonical)  # noqa: E402
from cli.permute.trace import codec  # noqa: E402

CONF = REPO / "conformance"
MANIFEST = CONF / "scenarios.toml"
ORACLE = CONF / "oracle"
RUNNER = REPO / "build" / "permute-run"
MAKE_GUEST = REPO / "tools" / "make_guest.py"
BUILD = REPO / "build" / "conformance"

MASK_BITS = (
    "_NTO_TIMEOUT_SEND", "_NTO_TIMEOUT_RECEIVE", "_NTO_TIMEOUT_REPLY",
    "_NTO_TIMEOUT_SIGSUSPEND", "_NTO_TIMEOUT_SIGWAITINFO",
    "_NTO_TIMEOUT_NANOSLEEP", "_NTO_TIMEOUT_MUTEX", "_NTO_TIMEOUT_CONDVAR",
    "_NTO_TIMEOUT_JOIN", "_NTO_TIMEOUT_INTR", "_NTO_TIMEOUT_SEM",
)


def build(source: Path, name: str) -> Path:
    out = BUILD / name
    out.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [sys.executable, str(MAKE_GUEST), "--source", str(source),
         "--name", name, "--instance", "0", "--out", str(out),
         "--build-dir", str(REPO / "build")],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        print(result.stdout, result.stderr)
        raise SystemExit(f"build failed: {source}")
    return out / f"proc_{name}__0.so"


def run(guest: Path, seed: int, trace: Path) -> tuple[str, dict]:
    env = {**os.environ, "PERMUTE_GUEST": str(guest)}
    result = subprocess.run([str(RUNNER), str(seed), str(trace)], env=env,
                            capture_output=True, text=True, timeout=120)
    fields = {}
    for line in result.stdout.splitlines():
        if "=" in line:
            key, _, value = line.partition("=")
            fields[key] = value
    return fields.get("OUTCOME", "INTERNAL"), fields


def oracle_dir() -> tuple[Path, str]:
    qnx = ORACLE / "qnx"
    if (qnx / "manifest.toml").is_file():
        return qnx, "qnx"
    return ORACLE / "simulator", "simulator"


def timer_mask_bits() -> tuple[int, str]:
    source = REPO / "scenarios" / "s03_timer_timeout" / "scenario.c"
    text = "\n".join(line.split("//", 1)[0]
                     for line in source.read_text().splitlines())
    present = [name for name in MASK_BITS if name in text]
    guest = build(source, "timer_bits")
    outcome, _ = run(guest, 1, BUILD / "timer_bits" / "trace.pmt")
    return len(present), outcome


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--record", action="store_true",
                        help="write simulator reference traces")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    if not RUNNER.is_file():
        raise SystemExit("missing build/permute-run; run make build")

    manifest = tomllib.loads(MANIFEST.read_text())
    defaults = manifest.get("defaults", {})
    target_dir, target_name = oracle_dir()

    if args.record:
        if target_name == "qnx":
            raise SystemExit("a QNX oracle is present; refusing to overwrite it")
        target_dir = ORACLE / "simulator"
        target_dir.mkdir(parents=True, exist_ok=True)

    records = []
    failures = 0
    executed = 0
    skipped = 0
    mandatory_executed = 0
    mandatory_skipped = 0

    for scenario in manifest.get("scenario", []):
        ident = scenario["id"]
        source = REPO / scenario["file"]
        if scenario.get("skip"):
            skipped += 1
            if not scenario.get("optional"):
                mandatory_skipped += 1
            records.append((ident, scenario["class"], "skip",
                            scenario["skip"], "-"))
            print(f"{ident} skip: {scenario['skip']}")
            continue

        guest = build(source, ident)
        seed = int(scenario.get("seed", defaults.get("seed", 1)))
        trace = BUILD / ident / "trace.pmt"
        outcome, fields = run(guest, seed, trace)

        if not trace.is_file():
            failures += 1
            records.append((ident, scenario["class"], "no trace", "", "-"))
            print(f"{ident} FAILED: no trace ({fields})")
            continue

        parsed = codec.read(trace)
        if not parsed.ok:
            failures += 1
            records.append((ident, scenario["class"], "bad trace", "", "-"))
            print(f"{ident} FAILED: trace does not verify")
            continue

        if args.record:
            (target_dir / f"{ident}.jsonl").write_text(to_jsonl(parsed.records))
            (target_dir / f"{ident}.outcome").write_text(outcome + "\n")

        oracle_path = target_dir / f"{ident}.jsonl"
        if not oracle_path.is_file():
            failures += 1
            records.append((ident, scenario["class"], "no oracle", "", "-"))
            print(f"{ident} FAILED: no oracle at {oracle_path}")
            continue

        events_a, deps_a = canonicalise(parsed.records)
        events_b, deps_b = load_canonical(oracle_path)
        result = compare_events(events_a, deps_a, events_b, deps_b)

        expected_outcome = outcome
        outcome_path = target_dir / f"{ident}.outcome"
        if outcome_path.is_file():
            expected_outcome = outcome_path.read_text().strip()

        ok = result.equal and outcome == expected_outcome
        executed += 1
        if not scenario.get("optional"):
            mandatory_executed += 1
        if not ok:
            failures += 1
        records.append((ident, scenario["class"],
                        "ok" if ok else "FAILED",
                        f"{result.detail}; outcome {outcome}", target_name))
        if args.verbose or not ok:
            print(f"{ident} {outcome}: {result.detail}"
                  f"{'' if ok else ' (FAILED)'}")

    # The TimerTimeout mask check is not one of the twelve scenarios; it is the
    # plan's gate for the timeout surface.
    masks, mask_outcome = timer_mask_bits()
    mask_ok = masks == len(MASK_BITS) and mask_outcome == "CLEAN"
    if not mask_ok:
        failures += 1
    print(f"timer mask bits: {masks}/{len(MASK_BITS)} ({mask_outcome})"
          f"{'' if mask_ok else ' (FAILED)'}")

    source_note = (
        "QNX capture" if target_name == "qnx"
        else "simulator reference (not a QNX capture)")

    report = [f"<!-- SPDX-License-Identifier: Apache-2.0 -->", "",
              "# Conformance report", "",
              f"**Oracle source:** {source_note}  ",
              f"**Executed:** {executed}  **Skipped:** {skipped}  "
              f"**Failures:** {failures}  ",
              f"**Mandatory executed:** {mandatory_executed}/12  "
              f"**Mandatory skipped:** {mandatory_skipped}", "",
              "| ID | Behaviour | Result | Detail | Oracle |",
              "|---|---|---|---|---|"]
    for ident, klass, status, detail, oracle in records:
        report.append(f"| {ident} | {klass} | {status} | {detail} | {oracle} |")
    report += ["",
               f"TimerTimeout mask bits: {masks}/{len(MASK_BITS)}.", ""]
    if target_name != "qnx":
        report += [
            "> These references were produced by the simulator itself. They "
            "guard against regressions and exercise the canonicaliser and "
            "comparator; they are **not** evidence of QNX fidelity. The "
            "physical SDP capture step is documented in "
            "`docs/CONFORMANCE.md` and has not been executed.", ""]
    (CONF / "REPORT.md").write_text("\n".join(report))

    print(f"conformance: {executed} executed, {skipped} skipped, "
          f"{failures} failure(s); mandatory {mandatory_executed}/12 executed; "
          f"oracle: {source_note}")
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
