#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Build a bootable QNX 8.0 x86_64 image containing every conformance
# scenario, boot it headless under QEMU, and require 14/14 to return 0.
#
# Usage: tools/qnx_image.sh [--sdp DIR] [--work DIR] [--evidence DIR]
#                           [--timeout SECONDS]
#
# Requires the QNX SDP 8.0 (qcc, mkqnximage), qemu-system-x86_64, and a
# writable /dev/kvm for the fast path (TCG is used otherwise).
#
# The generated system_files.custom uses mkqnx6fsimg's destination=source
# syntax; sources resolve through --repos, not as absolute paths. The boot
# runner puts every command on one line because mkqnximage's preprocessor
# prefixes continuation lines with '@'.

set -euo pipefail

REPO=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
SDP=${QNX_SDP:-$HOME/qnx800}
WORK=$REPO/build/qnx-image
EVIDENCE=
TIMEOUT=180

usage() {
    sed -n '4,16p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
    case $1 in
        --sdp) SDP=$2; shift 2 ;;
        --work) WORK=$2; shift 2 ;;
        --evidence) EVIDENCE=$2; shift 2 ;;
        --timeout) TIMEOUT=$2; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

[ -f "$SDP/qnxsdp-env.sh" ] || {
    echo "error: no QNX SDP at $SDP (set QNX_SDP or use --sdp)" >&2
    exit 1
}
command -v qemu-system-x86_64 >/dev/null 2>&1 || {
    echo "error: qemu-system-x86_64 is not installed" >&2
    exit 1
}

# shellcheck disable=SC1091
. "$SDP/qnxsdp-env.sh" >/dev/null

mkdir -p "$WORK/bin" "$WORK/local/snippets"
# mkqnx6fsimg resolves --repos against its own cwd, so keep this absolute.
WORK=$(realpath "$WORK")
WORK_REL=$WORK
case $WORK in "$REPO"/*) WORK_REL=${WORK#"$REPO"/} ;; esac

# 1. Cross-build every scenario and record the exact toolchain.
( cd "$REPO" && QNX_SDP="$SDP" ./tools/qnx_build_scenarios.sh "$WORK_REL/bin" ) \
    | tee "$WORK/build.log"

# 2. Stage the binaries in the system partition.
: > "$WORK/local/snippets/system_files.custom"
for bin in "$WORK"/bin/c*; do
    name=$(basename "$bin")
    echo "usr/bin/$name=$name" >> "$WORK/local/snippets/system_files.custom"
done

# 3. Boot runner. Keep the list on one line (see the header note).
{
    echo "# generated by tools/qnx_image.sh"
    echo 'echo "=== PERMUTE CONFORMANCE BEGIN $(date) ==="'
    echo 'uname -a'
    echo 'echo "HOSTNAME `hostname`"'
    echo 'echo "UID `id -u` USER `id -un`"'
    printf 'for n in'
    for bin in "$WORK"/bin/c*; do printf ' %s' "$(basename "$bin")"; done
    echo
    echo 'do'
    echo '    /system/usr/bin/$n'
    echo '    echo "RESULT $n rc=$?"'
    echo 'done'
    echo 'echo "=== PERMUTE CONFORMANCE END $(date) ==="'
} > "$WORK/local/snippets/post_start.custom"

# 4. Build the image. --repos makes the scenarios visible to mkqnx6fsimg.
( cd "$WORK" && mkqnximage --noprompt --type=qemu --arch=x86_64 \
    --cpu=4 --ram=2G --hostname=permute \
    --repos="$WORK/bin:$QNX_TARGET" --build=all --force ) \
    | tee "$WORK/mkqnximage.log"

# 5. Boot headless until the runner prints its end marker, then stop QEMU.
KVM=()
if [ -w /dev/kvm ]; then
    KVM=(-enable-kvm -cpu host)
fi
rm -f "$WORK/serial.log"
qemu-system-x86_64 "${KVM[@]}" -smp 4 -m 2G \
    -kernel "$WORK/output/ifs.bin" \
    -drive file="$WORK/output/disk-qemu.vmdk",if=ide,id=drv0 \
    -display none -serial file:"$WORK/serial.log" -monitor none -no-reboot &
qpid=$!
trap 'kill "$qpid" 2>/dev/null || true' EXIT

finished=0
for _ in $(seq 1 "$TIMEOUT"); do
    if grep -q "PERMUTE CONFORMANCE END" "$WORK/serial.log" 2>/dev/null; then
        finished=1
        break
    fi
    kill -0 "$qpid" 2>/dev/null || break
    sleep 1
done
kill "$qpid" 2>/dev/null || true
wait "$qpid" 2>/dev/null || true
trap - EXIT

if [ "$finished" -ne 1 ]; then
    echo "error: conformance did not finish within ${TIMEOUT}s" >&2
    echo "see $WORK/serial.log" >&2
    exit 1
fi

# 6. Assert the result, not just that the image booted.
results=$(grep -c '^RESULT ' "$WORK/serial.log" || true)
passed=$(grep -c '^RESULT .* rc=0' "$WORK/serial.log" || true)
expected=$(find "$WORK/bin" -maxdepth 1 -type f -name 'c*' | wc -l)
if [ "$results" -ne "$expected" ] || [ "$passed" -ne "$expected" ]; then
    echo "error: $passed/$results scenarios returned 0 (expected $expected)" >&2
    grep '^RESULT ' "$WORK/serial.log" >&2 || true
    exit 1
fi

# 7. Record provenance next to the logs.
uname_line=$(grep -A1 "PERMUTE CONFORMANCE BEGIN" "$WORK/serial.log" \
    | tail -1 | tr -d '\r')
baseline="QNX SDP 8.0"
if [ -d "$SDP/.packages/metadata/com.qnx.qnx800" ]; then
    version_dir=$(find "$SDP/.packages/metadata/com.qnx.qnx800" \
        -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2>/dev/null \
        | sort -V | tail -1)
    if [ -n "$version_dir" ]; then
        baseline="com.qnx.qnx800/$version_dir"
    fi
fi
commit=$(git -C "$REPO" rev-parse HEAD)
if [ -n "$(git -C "$REPO" status --porcelain -- conformance/scenarios abi)" ]; then
    commit="$commit (target sources dirty)"
fi

{
    echo "SDP baseline: $baseline"
    echo "uname: $uname_line"
    echo "disk-qemu sha256: $(sha256sum "$WORK/output/disk-qemu" | cut -d' ' -f1)"
    echo "ifs.bin sha256:   $(sha256sum "$WORK/output/ifs.bin" | cut -d' ' -f1)"
    echo "commit: $commit"
    echo "qemu: $(qemu-system-x86_64 --version | head -1), -smp 4 -m 2G"
} > "$WORK/manifest.log"

{
    printf 'qemu-system-x86_64'
    if [ ${#KVM[@]} -gt 0 ]; then printf ' %s' "${KVM[@]}"; fi
    printf ' -smp 4 -m 2G \\\n'
    printf '  -kernel output/ifs.bin \\\n'
    printf '  -drive file=output/disk-qemu.vmdk,if=ide,id=drv0 \\\n'
    printf '  -display none -serial file:serial.log -monitor none -no-reboot\n'
} > "$WORK/qemu.log"

if [ -n "$EVIDENCE" ]; then
    mkdir -p "$EVIDENCE"
    cp "$WORK/build.log" "$WORK/serial.log" "$WORK/manifest.log" \
        "$WORK/qemu.log" "$EVIDENCE/"
fi

sed -n '/PERMUTE CONFORMANCE BEGIN/,/PERMUTE CONFORMANCE END/p' "$WORK/serial.log"
echo "QNX target run: $passed/$results scenarios rc=0"
echo "evidence: ${EVIDENCE:-$WORK}"
